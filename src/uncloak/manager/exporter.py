"""
Enterprise SIEM & SOC Telemetry Exporter for Uncloak Central Manager.
Formats alerts into Syslog CEF (RFC 5424), STIX 2.1 JSON, and Sigma detection rules.
"""

from __future__ import annotations

import json
import time
from typing import Any


class SiemExporter:
    """Exports validated C2 alerts to enterprise SIEM platforms and threat intelligence hubs."""

    @staticmethod
    def to_cef(alert: dict[str, Any]) -> str:
        """
        Formats an alert as an ArcSight Common Event Format (CEF) string.
        Standard format for Splunk, Wazuh, and Micro Focus ArcSight.
        """
        device_vendor = "Uncloak"
        device_product = "BeaconHunter"
        device_version = "0.1.0"
        device_event_class_id = "C2_BEACON_DETECTED"
        name = "High-Confidence C2 Beaconing Channel Isolated"
        severity = "10" if alert.get("threat_score", 0.0) >= 0.85 else "7"

        # Extensions
        ext = (
            f"src={alert.get('host_ip', '127.0.0.1')} "
            f"dst={alert.get('remote_ip', '0.0.0.0')} "
            f"dpt={alert.get('remote_port', 443)} "
            f"proto=tcp "
            f"dproc={alert.get('process_name', 'unknown.exe')} "
            f"sproc={alert.get('pid', 0)} "
            f"cs1={alert.get('process_guid', '')} cs1Label=ProcessGuid "
            f"cs2={alert.get('process_sha256', '')} cs2Label=ProcessSHA256 "
            f"cn1={alert.get('threat_score', 0.0)} cn1Label=ThreatScore"
        )

        return f"CEF:0|{device_vendor}|{device_product}|{device_version}|{device_event_class_id}|{name}|{severity}|{ext}"

    @staticmethod
    def to_stix_bundle(alert: dict[str, Any]) -> dict[str, Any]:
        """
        Generates a STIX 2.1 Indicator and Observed-Data bundle from an alert.
        """
        now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        indicator_id = f"indicator--{alert.get('process_guid', 'uncloak-c2-beacon')}"
        remote_ip = alert.get("remote_ip", "0.0.0.0")

        return {
            "type": "bundle",
            "id": f"bundle--{alert.get('alert_id', 'uncloak-bundle')}",
            "objects": [
                {
                    "type": "indicator",
                    "spec_version": "2.1",
                    "id": indicator_id,
                    "created": now,
                    "modified": now,
                    "name": f"C2 Infrastructure: {remote_ip}",
                    "pattern": f"[ipv4-addr:value = '{remote_ip}']",
                    "pattern_type": "stix",
                    "valid_from": now,
                }
            ],
        }

    @staticmethod
    def to_sigma_rule(alert: dict[str, Any]) -> str:
        """
        Generates an automated Sigma YAML detection rule for SOC SIEM deployment.
        """
        process_name = alert.get("process_name", "malicious.exe")
        remote_ip = alert.get("remote_ip", "193.26.158.114")

        return f"""title: Automated C2 Eviction - {process_name}
id: {alert.get('process_guid', 'uncloak-auto-rule')}
status: experimental
description: Auto-generated by Uncloak upon surgical C2 socket eviction
references:
    - https://github.com/OussamaBelhane/uncloak
author: Uncloak EDR Automation
date: {time.strftime('%Y/%m/%d')}
logsource:
    category: network_connection
    product: windows
detection:
    selection:
        Image|endswith: '\\{process_name}'
        DestinationIp: '{remote_ip}'
        DestinationPort: 443
    condition: selection
falsepositives:
    - Unknown
level: critical
"""
